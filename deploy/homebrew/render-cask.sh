#!/bin/sh
# Writes the Homebrew cask for one release to stdout.
#
#   deploy/homebrew/render-cask.sh 0.1.0 SHA256SUMS > benchpod-desktop.rb
#
# SHA256SUMS is the file attached to that release. The homebrew workflow runs this when a release
# is published and pushes the result to embeddedci-com/homebrew-tap, so
#
#   brew install --cask embeddedci-com/tap/benchpod-desktop
#
# installs the app. The app is not code-signed: the cask removes the download quarantine after
# installing, which is what makes it open without a Gatekeeper prompt.
set -eu

version=${1:?usage: render-cask.sh VERSION SHA256SUMS}
sums=${2:?usage: render-cask.sh VERSION SHA256SUMS}

sha() {
  s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "render-cask.sh: $1 is not in $sums" >&2; exit 1; }
  echo "$s"
}
arm=$(sha "BenchPod.Desktop_${version}_aarch64.dmg")
intel=$(sha "BenchPod.Desktop_${version}_x64.dmg")

cat <<CASK
# Generated by deploy/homebrew/render-cask.sh in embeddedci-com/benchpod-desktop on release.
# Edit it there, not here: the next release overwrites this file.
cask "benchpod-desktop" do
  arch arm: "aarch64", intel: "x64"

  version "${version}"
  sha256 arm:   "${arm}",
         intel: "${intel}"

  url "https://github.com/embeddedci-com/benchpod-desktop/releases/download/v#{version}/BenchPod.Desktop_#{version}_#{arch}.dmg"
  name "BenchPod Desktop"
  desc "AI agent that tests and debugs your board with a BenchPod"
  homepage "https://github.com/embeddedci-com/benchpod-desktop"

  livecheck do
    skip "Updated on release."
  end

  depends_on :macos

  app "BenchPod Desktop.app"

  # Not code-signed yet: without this, macOS refuses to open the app.
  postflight_steps do
    run "/usr/bin/xattr",
        args:         ["-dr", "com.apple.quarantine", "{{appdir}}/BenchPod Desktop.app"],
        must_succeed: false
  end

  zap trash: [
    "~/Library/Application Support/com.embeddedci.benchpod-desktop",
    "~/Library/Application Support/benchpod-desktop",
    "~/Library/Caches/com.embeddedci.benchpod-desktop",
    "~/Library/WebKit/com.embeddedci.benchpod-desktop",
  ]
end
CASK
